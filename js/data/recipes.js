// 組み込みレシピ（分量はすべて2人分の目安）
//
// R(id, 料理名, 種類, 主な食材, ジャンル, 調理時間(分), カロリー(kcal/1人分), 絵文字, タグ, 材料, 作り方)
//  - 種類: 主菜 / 副菜 / 汁物
//  - 主な食材: 肉 / 魚 / 卵・豆腐 / 麺・丼 / 野菜 / 海藻・きのこ / その他
//  - ジャンル: 和 / 洋 / 中 / その他（韓国・エスニックなど）
//  - タグ: スペース区切り。調理時間20分以内には「時短」が自動で付きます
//  - 材料: 「材料名 分量」を「、」で区切る。分量の書き方をそろえると買い物リストで合算されます
//  - カロリーはご飯を含まない目安（丼・麺類は主食込み）
// ※ b01〜b48 は初期バージョンからのID。保存済みの献立・お気に入りが参照するので変えないこと。

export const CATEGORIES = ['主菜', '副菜', '汁物'];
export const MAIN_INGREDIENTS = ['肉', '魚', '卵・豆腐', '麺・丼', '野菜', '海藻・きのこ', 'その他'];
export const CUISINES = ['和', '洋', '中', 'その他'];
export const TAGS = ['時短', '定番', '作り置き', '節約', 'ヘルシー', '子ども向け', 'お弁当', 'ボリューム'];
export const QUICK_MINUTES = 20;

const DEFAULT_EMOJI = { 主菜: '🍽️', 副菜: '🥗', 汁物: '🥣' };

function parseIngredients(text) {
  return text
    .split('、')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => {
      const i = s.lastIndexOf(' ');
      return i < 0 ? { name: s, amount: '' } : { name: s.slice(0, i).trim(), amount: s.slice(i + 1).trim() };
    });
}

function withAutoTags(tags, time) {
  const list = Array.isArray(tags) ? [...tags] : String(tags || '').split(/\s+/).filter(Boolean);
  if (Number(time) <= QUICK_MINUTES && !list.includes('時短')) list.unshift('時短');
  if (Number(time) > QUICK_MINUTES) return list.filter((t) => t !== '時短');
  return list;
}

/** 自作レシピや古いデータに足りない項目を補う */
export function normalizeRecipe(r) {
  return {
    ...r,
    cuisine: CUISINES.includes(r.cuisine) ? r.cuisine : '和',
    kcal: Number(r.kcal) > 0 ? Number(r.kcal) : null,
    emoji: r.emoji || DEFAULT_EMOJI[r.category] || '🍽️',
    tags: withAutoTags(r.tags, r.time),
    ingredients: r.ingredients || [],
    steps: r.steps || [],
  };
}

const R = (id, name, category, main, cuisine, time, kcal, emoji, tags, ingredients, steps) => ({
  id, name, category, main, cuisine, time, kcal, emoji,
  tags: withAutoTags(tags, time),
  ingredients: parseIngredients(ingredients),
  steps,
  builtin: true,
});

